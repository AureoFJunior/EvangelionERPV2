        public async Task<PaginatedResultDTO<OpportunityDTO>> GetOpportunitiesAsync(Guid enterpriseId, OpportunityFilterDTO filter)
        {
            EnsureRadarEnabled();
            filter ??= new OpportunityFilterDTO();

            var opportunities = await SafeGetAllAsync(
                _opportunityRepository,
                BuildOpportunityPredicate(enterpriseId, filter));

            var filtered = ApplySort(opportunities, filter).ToList();
            var total = filtered.Count;
            var page = Math.Max(1, filter.Page);
            var pageSize = Math.Clamp(filter.PageSize <= 0 ? 25 : filter.PageSize, 1, 200);

            var paged = filtered
                .Skip((page - 1) * pageSize)
                .Take(pageSize)
                .ToList();

            var dtoItems = await MapOpportunitiesAsync(paged);

            return new PaginatedResultDTO<OpportunityDTO>
            {
                Items = dtoItems,
                TotalItems = total,
                Page = page,
                PageSize = pageSize
            };
        }

        public async Task<OpportunityDTO?> GetOpportunityByIdAsync(Guid id, Guid enterpriseId)
        {
            EnsureRadarEnabled();

            var opportunity = await _opportunityRepository.GetByIdAsync(id);
            if (opportunity == null || opportunity.IsActive != true || opportunity.EnterpriseId != enterpriseId)
                return null;

            var mapped = await MapOpportunitiesAsync([opportunity]);
            return mapped.FirstOrDefault();
        }

        public async Task<OpportunityFeedbackDTO> AddFeedbackAsync(
            Guid enterpriseId,
            Guid opportunityId,
            Guid? userId,
            OpportunityFeedbackRequestDTO request,
            bool canApproveExecution)
        {
            EnsureRadarEnabled();
            request ??= new OpportunityFeedbackRequestDTO();

            var normalizedStatus = NormalizeStatus(request.Status);
            if (!ValidFeedbackStatuses.Contains(normalizedStatus))
                throw new InsertDatabaseException("Invalid feedback status. Use in_analysis, accepted, rejected, ignored or implemented.");

            if (ManagedFeedbackStatuses.Contains(normalizedStatus) && !canApproveExecution)
                throw new InsertDatabaseException("Only managers can accept or implement opportunities.");

            var opportunity = await _opportunityRepository.GetByIdAsync(opportunityId);
            if (opportunity == null || opportunity.IsActive != true || opportunity.EnterpriseId != enterpriseId)
                throw new NotFoundDatabaseException("Opportunity was not found for this enterprise.");

            var now = DateTime.UtcNow;
            var feedback = new OpportunityFeedback
            {
                Id = Guid.NewGuid(),
                OpportunityId = opportunityId,
                UserId = userId,
                Status = normalizedStatus,
                Comment = request.Comment?.Trim() ?? string.Empty,
                MetadataJson = string.IsNullOrWhiteSpace(request.MetadataJson) ? "{}" : request.MetadataJson,
                RealRevenueImpact = request.RealRevenueImpact,
                RealMarginImpact = request.RealMarginImpact,
                RealCashImpact = request.RealCashImpact,
                CreatedAt = now,
                UpdatedAt = now,
                IsActive = true
            };

            await _feedbackRepository.CreateAsync(feedback);

            opportunity.Status = normalizedStatus switch
            {
                FeedbackInAnalysis => StatusInAnalysis,
                FeedbackAccepted => StatusAccepted,
                FeedbackImplemented => StatusExecuted,
                FeedbackRejected => StatusArchived,
                _ => StatusArchived
            };

            opportunity.UpdatedAt = now;
            opportunity.LastEvaluatedAt = now;
            _opportunityRepository.Update(opportunity);
            await _opportunityRepository.CommitAsync();

            FeedbackCounter.WithLabels(normalizedStatus).Inc();
            await UpdateKpiGaugesAsync(enterpriseId);

            return new OpportunityFeedbackDTO
            {
                Id = feedback.Id,
                OpportunityId = feedback.OpportunityId,
                UserId = feedback.UserId,
                Status = feedback.Status,
                Comment = feedback.Comment,
                MetadataJson = feedback.MetadataJson,
                RealRevenueImpact = feedback.RealRevenueImpact,
                RealMarginImpact = feedback.RealMarginImpact,
                RealCashImpact = feedback.RealCashImpact,
                CreatedAt = feedback.CreatedAt
            };
        }

        public async Task<OpportunityRunLogDTO> RecomputeAsync(
            Guid enterpriseId,
            Guid? requestedByUserId,
            OpportunityRecomputeRequestDTO request,
            string triggerType)
        {
            EnsureRadarEnabled();
            request ??= new OpportunityRecomputeRequestDTO();

            var runId = Guid.NewGuid();
            var now = DateTime.UtcNow;
            var historyWindowDays = request.HistoryWindowDays > 0
                ? request.HistoryWindowDays
                : _settings.DefaultHistoryWindowDays;
            var minSampleOrders = Math.Max(2, _settings.MinimumSampleOrders);

            var runLog = new OpportunityRunLog
            {
                Id = Guid.NewGuid(),
                RunId = runId,
                EnterpriseId = enterpriseId,
                RequestedByUserId = requestedByUserId,
                TriggerType = string.IsNullOrWhiteSpace(triggerType) ? "manual" : triggerType.ToLowerInvariant(),
                Status = "running",
                StartedAt = now,
                CorrelationId = Activity.Current?.Id ?? Guid.NewGuid().ToString("N", CultureInfo.InvariantCulture),
                CreatedAt = now,
                UpdatedAt = now,
                IsActive = true
            };

            await _runLogRepository.CreateAsync(runLog);
            await _runLogRepository.CommitAsync();

            var stopwatch = Stopwatch.StartNew();

            using var _ = RunDurationHistogram.NewTimer();
            using (LogContext.PushProperty("run_id", runId))
            {
                try
                {
                    Log.Information("Radar recompute started for enterprise {EnterpriseId}", enterpriseId);
                    var windowStart = now.Date.AddDays(-historyWindowDays);
                    var context = await BuildRadarContextAsync(enterpriseId, windowStart, historyWindowDays);
                    var candidates = DetectOpportunities(context, minSampleOrders);
                    if (candidates.Count == 0 && minSampleOrders > 2)
                    {
                        candidates = DetectOpportunities(context, 2);
                    }

                    var prioritized = Prioritize(candidates);

                    var persistResult = await UpsertOpportunitiesAsync(
                        enterpriseId,
                        runId,
                        prioritized,
                        request.OnlyOpenOpportunities,
                        now);

                    stopwatch.Stop();

                    runLog.Status = "completed";
                    runLog.TotalGenerated = persistResult.Generated;
                    runLog.TotalUpdated = persistResult.Updated;
                    runLog.TotalArchived = persistResult.Archived;
                    runLog.DurationMs = (int)stopwatch.ElapsedMilliseconds;
                    runLog.DetectorStatsJson = JsonSerializer.Serialize(persistResult.GeneratedByType);
                    runLog.FinishedAt = DateTime.UtcNow;
                    runLog.UpdatedAt = DateTime.UtcNow;
                    _runLogRepository.Update(runLog);
                    await _runLogRepository.CommitAsync();

                    ProcessingTimeGauge.WithLabels(enterpriseId.ToString()).Set(runLog.DurationMs);

                    foreach (var item in persistResult.GeneratedByType)
                    {
                        GeneratedCounter.WithLabels(item.Key).Inc(item.Value);
                    }

                    await UpdateKpiGaugesAsync(enterpriseId);

                    Log.Information(
                        "Radar recompute finished for enterprise {EnterpriseId}. generated={Generated}, updated={Updated}, archived={Archived}, durationMs={DurationMs}",
                        enterpriseId,
                        persistResult.Generated,
                        persistResult.Updated,
                        persistResult.Archived,
                        runLog.DurationMs);

                    return MapRunLog(runLog);
                }
                catch (Exception ex)
                {
                    stopwatch.Stop();

                    runLog.Status = "failed";
                    runLog.ErrorMessage = ex.Message;
                    runLog.DurationMs = (int)stopwatch.ElapsedMilliseconds;
                    runLog.FinishedAt = DateTime.UtcNow;
                    runLog.UpdatedAt = DateTime.UtcNow;
                    _runLogRepository.Update(runLog);
                    await _runLogRepository.CommitAsync();

                    Log.Error(ex, "Radar recompute failed for enterprise {EnterpriseId}", enterpriseId);
                    throw;
                }
            }
        }

        public async Task<OpportunitySummaryDTO> GetSummaryAsync(Guid enterpriseId)
        {
            EnsureRadarEnabled();
            var opportunities = await SafeGetAllAsync(_opportunityRepository,
                x => x.IsActive == true && x.EnterpriseId == enterpriseId);

            var runLogs = await SafeGetAllAsync(_runLogRepository,
                x => x.IsActive == true && x.EnterpriseId == enterpriseId && x.Status == "completed");

            var feedbacks = await GetFeedbacksByOpportunityIdsAsync(opportunities.Select(o => o.Id));

            var total = opportunities.Count;
            var accepted = opportunities.Count(x => x.Status == StatusAccepted || x.Status == StatusExecuted);
            var executed = opportunities.Count(x => x.Status == StatusExecuted);

            var estimatedMarginOnExecuted = opportunities
                .Where(x => x.Status == StatusExecuted)
                .Sum(x => x.EstimatedMarginImpact);

            var realMarginOnImplemented = feedbacks
                .Where(x => x.Status == FeedbackImplemented)
                .Sum(x => x.RealMarginImpact ?? 0);

            var acceptanceRate = total <= 0 ? 0 : (double)accepted / total;
            var implementationRate = accepted <= 0 ? 0 : (double)executed / accepted;
            var uplift = estimatedMarginOnExecuted <= 0
                ? 0
                : realMarginOnImplemented / estimatedMarginOnExecuted;

            var lastRun = runLogs
                .OrderByDescending(x => x.StartedAt)
                .FirstOrDefault();

            var summary = new OpportunitySummaryDTO
            {
                Total = total,
                NewCount = opportunities.Count(x => x.Status == StatusNew),
                InAnalysisCount = opportunities.Count(x => x.Status == StatusInAnalysis),
                AcceptedCount = opportunities.Count(x => x.Status == StatusAccepted),
                ExecutedCount = opportunities.Count(x => x.Status == StatusExecuted),
                ArchivedCount = opportunities.Count(x => x.Status == StatusArchived),
                EstimatedRevenueImpact = opportunities.Sum(x => x.EstimatedRevenueImpact),
                EstimatedMarginImpact = opportunities.Sum(x => x.EstimatedMarginImpact),
                EstimatedCashImpact = opportunities.Sum(x => x.EstimatedCashImpact),
                AcceptanceRate = Math.Round(acceptanceRate, 4),
                ImplementationRate = Math.Round(implementationRate, 4),
                RealVsEstimatedUplift = Math.Round(uplift, 4),
                AverageProcessingTimeMs = runLogs.Count == 0 ? 0 : Math.Round(runLogs.Average(x => x.DurationMs), 2),
                LastRunId = lastRun?.RunId,
                LastRunAt = lastRun?.StartedAt,
                OpportunitiesByType = opportunities
                    .GroupBy(x => x.Type)
                    .ToDictionary(x => x.Key, x => x.Count())
            };

            AcceptanceRateGauge.WithLabels(enterpriseId.ToString()).Set(summary.AcceptanceRate);
            ImplementationRateGauge.WithLabels(enterpriseId.ToString()).Set(summary.ImplementationRate);
            UpliftRealVsEstimatedGauge.WithLabels(enterpriseId.ToString()).Set(summary.RealVsEstimatedUplift);

            return summary;
        }

        private static Expression<Func<Opportunity, bool>> BuildOpportunityPredicate(Guid enterpriseId, OpportunityFilterDTO filter)
        {
            var normalizedType = string.IsNullOrWhiteSpace(filter.Type)
                ? null
                : filter.Type.Trim().ToLowerInvariant();

            var normalizedStatus = string.IsNullOrWhiteSpace(filter.Status)
                ? null
                : filter.Status.Trim().ToLowerInvariant();

            var minScore = filter.MinScore;
            var maxScore = filter.MaxScore;
            var minImpact = filter.MinImpact;
            var maxImpact = filter.MaxImpact;
            var startDate = filter.StartDate;
            var endDate = filter.EndDate;

            return x => x.IsActive == true
                        && x.EnterpriseId == enterpriseId
                        && (normalizedType == null || x.Type.ToLower() == normalizedType)
                        && (normalizedStatus == null || x.Status.ToLower() == normalizedStatus)
                        && (!minScore.HasValue || x.ConfidenceScore >= minScore.Value)
                        && (!maxScore.HasValue || x.ConfidenceScore <= maxScore.Value)
                        && (!minImpact.HasValue || x.EstimatedMarginImpact >= minImpact.Value)
                        && (!maxImpact.HasValue || x.EstimatedMarginImpact <= maxImpact.Value)
                        && (!startDate.HasValue || x.DetectedAt >= startDate.Value)
                        && (!endDate.HasValue || x.DetectedAt <= endDate.Value);
        }

        private IEnumerable<Opportunity> ApplySort(IEnumerable<Opportunity> source, OpportunityFilterDTO filter)
        {
            var query = source;
            var sortBy = (filter.SortBy ?? "priority").Trim().ToLowerInvariant();
            var descending = filter.Descending;

            return sortBy switch
            {
                "score" => descending
                    ? query.OrderByDescending(x => x.ConfidenceScore).ThenByDescending(x => x.PriorityScore)
                    : query.OrderBy(x => x.ConfidenceScore).ThenBy(x => x.PriorityScore),
                "impact" => descending
                    ? query.OrderByDescending(x => x.EstimatedMarginImpact).ThenByDescending(x => x.PriorityScore)
                    : query.OrderBy(x => x.EstimatedMarginImpact).ThenBy(x => x.PriorityScore),
                "detected" => descending
                    ? query.OrderByDescending(x => x.DetectedAt)
                    : query.OrderBy(x => x.DetectedAt),
                "status" => descending
                    ? query.OrderByDescending(x => x.Status).ThenByDescending(x => x.PriorityScore)
                    : query.OrderBy(x => x.Status).ThenBy(x => x.PriorityScore),
                _ => descending
                    ? query.OrderByDescending(x => x.PriorityScore).ThenByDescending(x => x.ConfidenceScore)
                    : query.OrderBy(x => x.PriorityScore).ThenBy(x => x.ConfidenceScore)
            };
        }

        private async Task<List<OpportunityFeedback>> GetFeedbacksByOpportunityIdsAsync(IEnumerable<Guid> opportunityIds)
        {
            var result = new List<OpportunityFeedback>();
            var ids = opportunityIds.Distinct().ToList();
            if (ids.Count == 0)
                return result;

            foreach (var batch in ids.Chunk(1000))
            {
                var batchIds = batch.ToList();
                var feedbackBatch = await SafeGetAllAsync(
                    _feedbackRepository,
                    x => x.IsActive == true && batchIds.Contains(x.OpportunityId));

                if (feedbackBatch.Count > 0)
                    result.AddRange(feedbackBatch);
            }

            return result;
        }

        private async Task<List<OpportunityDTO>> MapOpportunitiesAsync(IReadOnlyCollection<Opportunity> opportunities)
        {
            if (opportunities.Count == 0)
                return [];

            var ids = opportunities.Select(x => x.Id).ToHashSet();

            var signals = await SafeGetAllAsync(_signalRepository,
                x => x.IsActive == true && ids.Contains(x.OpportunityId));

            var recommendations = await SafeGetAllAsync(_recommendationRepository,
                x => x.IsActive == true && ids.Contains(x.OpportunityId));

            var feedbacks = await SafeGetAllAsync(_feedbackRepository,
                x => x.IsActive == true && ids.Contains(x.OpportunityId));

            var signalsByOpportunity = signals
                .GroupBy(x => x.OpportunityId)
                .ToDictionary(x => x.Key, x => x.ToList());

            var recommendationByOpportunity = recommendations
                .GroupBy(x => x.OpportunityId)
                .ToDictionary(x => x.Key, x => x.OrderByDescending(r => r.CreatedAt).First());

            var feedbackByOpportunity = feedbacks
                .GroupBy(x => x.OpportunityId)
                .ToDictionary(x => x.Key, x => x.OrderByDescending(f => f.CreatedAt).ToList());

            return opportunities
                .Select(opportunity =>
                {
                    signalsByOpportunity.TryGetValue(opportunity.Id, out var opportunitySignals);
                    recommendationByOpportunity.TryGetValue(opportunity.Id, out var opportunityRecommendation);
                    feedbackByOpportunity.TryGetValue(opportunity.Id, out var opportunityFeedbacks);

                    return new OpportunityDTO
                    {
                        Id = opportunity.Id,
                        EnterpriseId = opportunity.EnterpriseId,
                        Type = opportunity.Type,
                        Status = opportunity.Status,
                        Title = opportunity.Title,
                        Description = opportunity.Description,
                        SourceRule = opportunity.SourceRule,
                        SourceModel = opportunity.SourceModel,
                        Hypothesis = opportunity.Hypothesis,
                        ExplainabilityJson = opportunity.ExplainabilityJson,
                        RunId = opportunity.RunId,
                        ConfidenceScore = Math.Round(opportunity.ConfidenceScore, 2),
                        EstimatedRevenueImpact = Math.Round(opportunity.EstimatedRevenueImpact, 2),
                        EstimatedMarginImpact = Math.Round(opportunity.EstimatedMarginImpact, 2),
                        EstimatedCashImpact = Math.Round(opportunity.EstimatedCashImpact, 2),
                        PriorityScore = Math.Round(opportunity.PriorityScore, 2),
                        DetectedAt = opportunity.DetectedAt,
                        LastEvaluatedAt = opportunity.LastEvaluatedAt,
                        Recommendation = opportunityRecommendation == null
                            ? null
                            : new OpportunityRecommendationDTO
                            {
                                Id = opportunityRecommendation.Id,
                                ActionTitle = opportunityRecommendation.ActionTitle,
                                ActionDescription = opportunityRecommendation.ActionDescription,
                                WhyRecommended = opportunityRecommendation.WhyRecommended,
                                ActionPayloadJson = opportunityRecommendation.ActionPayloadJson,
                                PriorityLabel = opportunityRecommendation.PriorityLabel
                            },
                        Signals = (opportunitySignals ?? [])
                            .OrderByDescending(x => x.SignalValue)
                            .Select(signal => new OpportunitySignalDTO
                            {
                                Id = signal.Id,
                                SignalType = signal.SignalType,
                                SignalKey = signal.SignalKey,
                                SignalValue = Math.Round(signal.SignalValue, 4),
                                Unit = signal.Unit,
                                MetadataJson = signal.MetadataJson,
                                SourceEntity = signal.SourceEntity,
                                SourceEntityId = signal.SourceEntityId,
                                CapturedAt = signal.CapturedAt
                            }).ToList(),
                        Feedbacks = (opportunityFeedbacks ?? [])
                            .Select(feedback => new OpportunityFeedbackDTO
                            {
                                Id = feedback.Id,
                                OpportunityId = feedback.OpportunityId,
                                UserId = feedback.UserId,
                                Status = feedback.Status,
                                Comment = feedback.Comment,
                                MetadataJson = feedback.MetadataJson,
                                RealRevenueImpact = feedback.RealRevenueImpact,
                                RealMarginImpact = feedback.RealMarginImpact,
                                RealCashImpact = feedback.RealCashImpact,
                                CreatedAt = feedback.CreatedAt
                            }).ToList()
                    };
                })
                .ToList();
        }

        private async Task<RadarDataContext> BuildRadarContextAsync(Guid enterpriseId, DateTime windowStart, int historyWindowDays)
        {
            var effectiveWindowStart = windowStart;
            var effectiveHistoryWindowDays = Math.Max(1, historyWindowDays);

            var orders = await SafeGetAllAsync(_orderRepository,
                x => x.IsActive == true
                     && x.EnterpriseId == enterpriseId
                     && x.CreatedAt >= windowStart);

            if (orders.Count == 0)
            {
                orders = await SafeGetAllAsync(_orderRepository,
                    x => x.IsActive == true
                         && x.EnterpriseId == enterpriseId);

                if (orders.Count > 0)
                {
                    effectiveWindowStart = orders.Min(x => x.CreatedAt).Date;
                    effectiveHistoryWindowDays = Math.Max(1, (DateTime.UtcNow.Date - effectiveWindowStart).Days + 1);
                }
            }

            var orderIds = orders.Select(x => x.Id).ToHashSet();

            var orderedProducts = orderIds.Count == 0
                ? []
                : await SafeGetAllAsync(_orderedProductRepository,
                    x => x.IsActive == true
                         && x.OrderId.HasValue
                         && orderIds.Contains(x.OrderId.Value));

            var productIds = orderedProducts.Select(x => x.ProductId).Distinct().ToHashSet();
            var products = productIds.Count == 0
                ? []
                : await SafeGetAllAsync(_productRepository,
                    x => x.IsActive == true
                         && x.EnterpriseId == enterpriseId
                         && productIds.Contains(x.Id));

            var customerIds = orders
                .Where(x => x.CustomerId.HasValue)
                .Select(x => x.CustomerId!.Value)
                .Distinct()
                .ToHashSet();

            var customers = customerIds.Count == 0
                ? []
                : await SafeGetAllAsync(_customerRepository,
                    x => x.IsActive == true
                         && x.EnterpriseId == enterpriseId
                         && customerIds.Contains(x.Id));

            var payableBills = await SafeGetAllAsync(_payableBillRepository,
                x => x.IsActive == true
                     && x.EnterpriseId == enterpriseId
                     && x.CreatedAt >= windowStart);

            if (payableBills.Count == 0)
            {
                payableBills = await SafeGetAllAsync(_payableBillRepository,
                    x => x.IsActive == true
                         && x.EnterpriseId == enterpriseId);
            }

            var payableBillIds = payableBills.Select(x => x.Id).ToHashSet();
            var payableItems = payableBillIds.Count == 0
                ? []
                : await SafeGetAllAsync(_payableBillProductRepository,
                    x => x.IsActive == true
                         && payableBillIds.Contains(x.PayableBillId));

            return new RadarDataContext
            {
                Orders = orders,
                OrderedProducts = orderedProducts,
                ProductsById = products.ToDictionary(x => x.Id, x => x),
                CustomersById = customers.ToDictionary(x => x.Id, x => x),
                PayableBills = payableBills,
                PayableItems = payableItems,
                WindowStart = effectiveWindowStart,
                HistoryWindowDays = effectiveHistoryWindowDays
            };
        }

        private List<OpportunityCandidate> DetectOpportunities(RadarDataContext context, int minSampleOrders)
        {
            var candidates = new List<OpportunityCandidate>();

            candidates.AddRange(DetectCrossSell(context, minSampleOrders));
            candidates.AddRange(DetectMarginBundles(context, minSampleOrders));
            candidates.AddRange(DetectSuppressedDemand(context));
            candidates.AddRange(DetectLowStock(context, minSampleOrders));
            candidates.AddRange(DetectSupplierHiddenCost(context, minSampleOrders));
            candidates.AddRange(DetectCommercialReallocation(context, minSampleOrders));

            return candidates;
        }

        private List<OpportunityCandidate> DetectCrossSell(RadarDataContext context, int minSampleOrders)
        {
            var orderProducts = BuildOrderProductSets(context);
            if (orderProducts.Count == 0)
                return [];

            var customerSegments = BuildCustomerSegments(context);
            var opportunities = new List<OpportunityCandidate>();
            var segmentValues = customerSegments.Values.Distinct().ToList();
            var demandOrderIds = ResolveDemandOrderScope(context.Orders);

            if (demandOrderIds.Count == 0)
                return [];

            if (segmentValues.Count == 0)
                segmentValues = ["all_customers"];

            foreach (var segmentValue in segmentValues)
            {
                var segmentOrderIds = segmentValue == "all_customers"
                    ? context.Orders
                        .Where(order => demandOrderIds.Contains(order.Id))
                        .Select(order => order.Id)
                        .ToList()
                    : context.Orders
                        .Where(order => order.CustomerId.HasValue
                                        && customerSegments.TryGetValue(order.CustomerId.Value, out var customerSegment)
                                        && customerSegment == segmentValue
                                        && demandOrderIds.Contains(order.Id))
                        .Select(order => order.Id)
                        .ToList();

                if (segmentOrderIds.Count < minSampleOrders)
                    continue;

                var pairs = BuildPairMetrics(orderProducts, segmentOrderIds);
                var trios = BuildTrioCounts(orderProducts, segmentOrderIds);

                var topPairs = pairs
                    .Where(pair => pair.SupportCount >= minSampleOrders && pair.Confidence >= 0.35)
                    .OrderByDescending(pair => pair.Confidence * pair.Support)
                    .Take(4)
                    .ToList();

