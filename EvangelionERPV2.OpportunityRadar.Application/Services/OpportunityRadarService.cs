        private static HashSet<Guid> ResolveDemandOrderScope(IEnumerable<Order> orders)
        {
            var finalizedOrderIds = orders
                .Where(order => FinalizedOrderStatuses.Contains(order.Status))
                .Select(order => order.Id)
                .ToHashSet();

            if (finalizedOrderIds.Count > 0)
                return finalizedOrderIds;

            return orders
                .Where(order => order.Status != (int)EnumOrderStatus.Refund)
                .Select(order => order.Id)
                .ToHashSet();
        }

        private Dictionary<Guid, HashSet<Guid>> BuildOrderProductSets(RadarDataContext context)
        {
            var demandOrderIds = ResolveDemandOrderScope(context.Orders);

            return context.OrderedProducts
                .Where(line => line.OrderId.HasValue && demandOrderIds.Contains(line.OrderId.Value))
                .GroupBy(line => line.OrderId!.Value)
                .ToDictionary(
                    group => group.Key,
                    group => group.Select(line => line.ProductId).ToHashSet());
        }

        private Dictionary<Guid, string> BuildCustomerSegments(RadarDataContext context)
        {
            var demandOrderIds = ResolveDemandOrderScope(context.Orders);

            var customerStats = context.Orders
                .Where(order => order.CustomerId.HasValue && demandOrderIds.Contains(order.Id))
                .GroupBy(order => order.CustomerId!.Value)
                .Select(group => new
                {
                    CustomerId = group.Key,
                    AverageTicket = group.Average(order => Math.Max(0, order.TotalValue))
                })
                .OrderBy(stat => stat.AverageTicket)
                .ToList();

            if (customerStats.Count == 0)
                return [];

            var lowerIndex = (int)Math.Floor((customerStats.Count - 1) * 0.33);
            var upperIndex = (int)Math.Floor((customerStats.Count - 1) * 0.66);
            var lowerThreshold = customerStats[lowerIndex].AverageTicket;
            var upperThreshold = customerStats[upperIndex].AverageTicket;

            return customerStats.ToDictionary(
                stat => stat.CustomerId,
                stat => stat.AverageTicket <= lowerThreshold
                    ? "value"
                    : stat.AverageTicket >= upperThreshold
                        ? "premium"
                        : "standard");
        }

        private static List<PairMetric> BuildPairMetrics(Dictionary<Guid, HashSet<Guid>> orderProducts, IEnumerable<Guid> orderIds)
        {
            var supportCounts = new Dictionary<(Guid, Guid), int>();
            var baseCounts = new Dictionary<Guid, int>();
            var scopedOrderIds = orderIds.ToHashSet();
            var totalOrders = 0;

            foreach (var orderEntry in orderProducts.Where(item => scopedOrderIds.Contains(item.Key)))
            {
                var products = orderEntry.Value.ToList();
                if (products.Count < 2)
                    continue;

                totalOrders++;

                foreach (var product in products)
                {
                    if (!baseCounts.TryAdd(product, 1))
                        baseCounts[product]++;
                }

                for (var i = 0; i < products.Count; i++)
                {
                    for (var j = i + 1; j < products.Count; j++)
                    {
                        var left = products[i];
                        var right = products[j];
                        var key = left.CompareTo(right) < 0 ? (left, right) : (right, left);
                        if (!supportCounts.TryAdd(key, 1))
                            supportCounts[key]++;
                    }
                }
            }

            if (totalOrders <= 0)
                return [];

            var result = new List<PairMetric>();
            foreach (var support in supportCounts)
            {
                var productA = support.Key.Item1;
                var productB = support.Key.Item2;
                var supportCount = support.Value;
                var supportRatio = (double)supportCount / totalOrders;
                var confA = baseCounts.TryGetValue(productA, out var baseA) && baseA > 0 ? (double)supportCount / baseA : 0;
                var confB = baseCounts.TryGetValue(productB, out var baseB) && baseB > 0 ? (double)supportCount / baseB : 0;

                result.Add(new PairMetric
                {
                    ProductA = productA,
                    ProductB = productB,
                    Support = supportRatio,
                    SupportCount = supportCount,
                    Confidence = Math.Max(confA, confB)
                });
            }

            return result;
        }

        private static Dictionary<HashSet<Guid>, int> BuildTrioCounts(Dictionary<Guid, HashSet<Guid>> orderProducts, IEnumerable<Guid> orderIds)
        {
            var scoped = orderIds.ToHashSet();
            var comparer = HashSet<Guid>.CreateSetComparer();
            var counts = new Dictionary<HashSet<Guid>, int>(comparer);

            foreach (var entry in orderProducts.Where(item => scoped.Contains(item.Key)))
            {
                var products = entry.Value.ToList();
                if (products.Count < 3)
                    continue;

                for (var i = 0; i < products.Count; i++)
                {
                    for (var j = i + 1; j < products.Count; j++)
                    {
                        for (var k = j + 1; k < products.Count; k++)
                        {
                            var trio = new HashSet<Guid> { products[i], products[j], products[k] };
                            if (!counts.TryAdd(trio, 1))
                                counts[trio]++;
                        }
                    }
                }
            }

            return counts;
        }

        private static Dictionary<Guid, double> BuildDailyConsumptionByProduct(RadarDataContext context)
        {
            if (context.OrderedProducts.Count == 0)
                return [];

            var orderById = context.Orders.ToDictionary(order => order.Id, order => order);
            var demandOrderIds = ResolveDemandOrderScope(context.Orders);

            var lines = context.OrderedProducts
                .Where(line => line.OrderId.HasValue
                               && orderById.ContainsKey(line.OrderId.Value)
                               && demandOrderIds.Contains(line.OrderId.Value))
                .ToList();

            return lines
                .GroupBy(line => line.ProductId)
                .ToDictionary(
                    group => group.Key,
                    group => group.Sum(line => line.Quantity) / Math.Max(1, context.HistoryWindowDays));
        }

        private static Dictionary<Guid, double> BuildAverageCostByProduct(RadarDataContext context)
        {
            if (context.PayableItems.Count == 0)
                return [];

            var validReceivedBillIds = context.PayableBills
                .Where(bill => bill.ProductsReceivedAt.HasValue)
                .Select(bill => bill.Id)
                .ToHashSet();

            var lines = context.PayableItems
                .Where(item => validReceivedBillIds.Count == 0 || validReceivedBillIds.Contains(item.PayableBillId))
                .ToList();

            if (lines.Count == 0)
                lines = context.PayableItems;

            return lines
                .GroupBy(item => item.ProductId)
                .ToDictionary(
                    group => group.Key,
                    group =>
                    {
                        var totalQuantity = group.Sum(item => item.Quantity);
                        if (totalQuantity <= 0)
                            return 0d;

                        var totalAmount = group.Sum(item => item.Quantity * item.UnitValue);
                        return totalAmount / totalQuantity;
                    });
        }

        private static double ResolveCoverageDays(Product product, IReadOnlyDictionary<Guid, double> dailyConsumption)
        {
            if (!dailyConsumption.TryGetValue(product.Id, out var consumption) || consumption <= 0)
                return double.PositiveInfinity;

            return Math.Max(0, product.StorageQuantity) / consumption;
        }

        private static double ComputeReworkRate(IReadOnlyList<PayableBill> bills, IReadOnlyList<PayableBillProduct> lines)
        {
            if (bills.Count < 2 || lines.Count == 0)
                return 0;

            var billsByDate = bills
                .OrderBy(bill => bill.CreatedAt)
                .ToList();

            var repeatedWithinWindow = 0;
            var totalChecks = 0;

            for (var i = 1; i < billsByDate.Count; i++)
            {
                var current = billsByDate[i];
                var previous = billsByDate[i - 1];
                var days = (current.CreatedAt - previous.CreatedAt).TotalDays;
                if (days < 0 || days > 10)
                    continue;

                var previousProducts = lines
                    .Where(line => line.PayableBillId == previous.Id)
                    .Select(line => line.ProductId)
                    .ToHashSet();

                var currentProducts = lines
                    .Where(line => line.PayableBillId == current.Id)
                    .Select(line => line.ProductId)
                    .ToHashSet();

                if (previousProducts.Count == 0 || currentProducts.Count == 0)
                    continue;

                totalChecks++;
                if (previousProducts.Overlaps(currentProducts))
                    repeatedWithinWindow++;
            }

            if (totalChecks == 0)
                return 0;

            return (double)repeatedWithinWindow / totalChecks;
        }

        private static string InferSupplierKey(string description)
        {
            if (string.IsNullOrWhiteSpace(description))
                return "unknown_supplier";

            var raw = description.Trim();
            var delimiters = new[] { " - ", ":", "|", "/", "\\" };

            foreach (var delimiter in delimiters)
            {
                var split = raw.Split(delimiter, StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);
                if (split.Length > 1 && split[0].Length >= 3)
                    return split[0].ToLowerInvariant();
            }

            var firstToken = raw.Split(' ', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
                .FirstOrDefault();

            return string.IsNullOrWhiteSpace(firstToken)
                ? "unknown_supplier"
                : firstToken.ToLowerInvariant();
        }

        private static string InferSalesChannel(Customer customer)
        {
            if (!string.IsNullOrWhiteSpace(customer.Document))
            {
                var digits = new string(customer.Document.Where(char.IsDigit).ToArray());
                if (digits.Length > 11)
                    return "b2b";
            }

            if (!string.IsNullOrWhiteSpace(customer.Email) && customer.Email.Contains("market", StringComparison.OrdinalIgnoreCase))
                return "marketplace";

            return "b2c";
        }

        private static string InferRegion(string? address)
        {
            if (string.IsNullOrWhiteSpace(address))
                return "unknown";

            var tokens = address
                .Split([',', ';', '|', '-'], StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
                .Reverse()
                .ToList();

            foreach (var token in tokens)
            {
                var normalized = token.Trim().ToUpperInvariant();
                if (normalized.Length == 2 && normalized.All(char.IsLetter))
                    return normalized;
            }

            var first = tokens.FirstOrDefault();
            if (string.IsNullOrWhiteSpace(first))
                return "unknown";

            return first.Trim().ToUpperInvariant();
        }

