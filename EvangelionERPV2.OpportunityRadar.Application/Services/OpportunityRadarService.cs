            ];
        }

        private List<OpportunityCandidate> Prioritize(IEnumerable<OpportunityCandidate> rawCandidates)
        {
            var candidates = rawCandidates
                .GroupBy(candidate => candidate.Fingerprint)
                .Select(group => group.OrderByDescending(item => item.ConfidenceScore).First())
                .ToList();

            if (candidates.Count == 0)
                return [];

            var maxImpact = candidates
                .Select(candidate => Math.Abs(candidate.EstimatedMarginImpact) + Math.Abs(candidate.EstimatedRevenueImpact * 0.2) + Math.Abs(candidate.EstimatedCashImpact * 0.1))
                .DefaultIfEmpty(1)
                .Max();

            foreach (var candidate in candidates)
            {
                var impact = Math.Abs(candidate.EstimatedMarginImpact)
                             + Math.Abs(candidate.EstimatedRevenueImpact * 0.2)
                             + Math.Abs(candidate.EstimatedCashImpact * 0.1);

                var impactScore = maxImpact <= 0 ? 0 : (impact / maxImpact) * 100;
                var priority = (candidate.ConfidenceScore * 0.6) + (impactScore * 0.4);
                candidate.PriorityScore = Clamp(priority, 0, 100);
                candidate.PriorityLabel = ResolvePriorityLabel(candidate.PriorityScore);
            }

            return candidates
                .OrderByDescending(candidate => candidate.PriorityScore)
                .ThenByDescending(candidate => candidate.ConfidenceScore)
                .ThenByDescending(candidate => candidate.EstimatedMarginImpact)
                .ToList();
        }

        private async Task<PersistResult> UpsertOpportunitiesAsync(
            Guid enterpriseId,
            Guid runId,
            IReadOnlyList<OpportunityCandidate> candidates,
            bool onlyOpenOpportunities,
            DateTime now)
        {
            var existing = await SafeGetAllAsync(_opportunityRepository,
                x => x.IsActive == true && x.EnterpriseId == enterpriseId);

            var existingByFingerprint = existing
                .Where(x => !string.IsNullOrWhiteSpace(x.Fingerprint))
                .ToDictionary(x => x.Fingerprint, x => x, StringComparer.OrdinalIgnoreCase);

            var createdByType = new Dictionary<string, double>(StringComparer.OrdinalIgnoreCase);
            var generated = 0;
            var updated = 0;

            foreach (var candidate in candidates)
            {
                if (existingByFingerprint.TryGetValue(candidate.Fingerprint, out var existingOpportunity))
                {
                    existingOpportunity.Type = candidate.Type;
                    existingOpportunity.Title = candidate.Title;
                    existingOpportunity.Description = candidate.Description;
                    existingOpportunity.SourceRule = candidate.SourceRule;
                    existingOpportunity.SourceModel = candidate.SourceModel;
                    existingOpportunity.Hypothesis = candidate.Hypothesis;
                    existingOpportunity.ExplainabilityJson = candidate.ExplainabilityJson;
                    existingOpportunity.RunId = runId;
                    existingOpportunity.ConfidenceScore = candidate.ConfidenceScore;
                    existingOpportunity.EstimatedRevenueImpact = candidate.EstimatedRevenueImpact;
                    existingOpportunity.EstimatedMarginImpact = candidate.EstimatedMarginImpact;
                    existingOpportunity.EstimatedCashImpact = candidate.EstimatedCashImpact;
                    existingOpportunity.PriorityScore = candidate.PriorityScore;
                    existingOpportunity.LastEvaluatedAt = now;
                    existingOpportunity.UpdatedAt = now;

                    if (existingOpportunity.Status == StatusArchived)
                        existingOpportunity.Status = StatusNew;

                    _opportunityRepository.Update(existingOpportunity);

                    await ReplaceSignalsAndRecommendationAsync(existingOpportunity.Id, candidate, now);
                    updated++;
                }
                else
                {
                    var opportunity = new Opportunity
                    {
                        Id = Guid.NewGuid(),
                        EnterpriseId = enterpriseId,
                        Type = candidate.Type,
                        Status = StatusNew,
                        Title = candidate.Title,
                        Description = candidate.Description,
                        SourceRule = candidate.SourceRule,
                        SourceModel = candidate.SourceModel,
                        Hypothesis = candidate.Hypothesis,
                        ExplainabilityJson = candidate.ExplainabilityJson,
                        Fingerprint = candidate.Fingerprint,
                        RunId = runId,
                        ConfidenceScore = candidate.ConfidenceScore,
                        EstimatedRevenueImpact = candidate.EstimatedRevenueImpact,
                        EstimatedMarginImpact = candidate.EstimatedMarginImpact,
                        EstimatedCashImpact = candidate.EstimatedCashImpact,
                        PriorityScore = candidate.PriorityScore,
                        DetectedAt = now,
                        LastEvaluatedAt = now,
                        CreatedAt = now,
                        UpdatedAt = now,
                        IsActive = true
                    };

                    await _opportunityRepository.CreateAsync(opportunity);

                    await CreateSignalsAsync(opportunity.Id, candidate.Signals, now);
                    await CreateRecommendationAsync(opportunity.Id, candidate, now);

                    generated++;
                    if (!createdByType.TryAdd(candidate.Type, 1))
                        createdByType[candidate.Type]++;

                    Log.Information(
                        "Opportunity recommendation generated. type={Type} title={Title} confidence={Score} marginImpact={MarginImpact} runId={RunId}",
                        candidate.Type,
                        candidate.Title,
                        Math.Round(candidate.ConfidenceScore, 2),
                        Math.Round(candidate.EstimatedMarginImpact, 2),
                        runId);
                }
            }

            var currentFingerprints = candidates
                .Select(candidate => candidate.Fingerprint)
                .ToHashSet(StringComparer.OrdinalIgnoreCase);

            var archived = 0;
            foreach (var opportunity in existing)
            {
                if (currentFingerprints.Contains(opportunity.Fingerprint))
                    continue;

                if (onlyOpenOpportunities && (opportunity.Status == StatusAccepted || opportunity.Status == StatusExecuted))
                    continue;

                if (opportunity.Status == StatusArchived)
                    continue;

                opportunity.Status = StatusArchived;
                opportunity.LastEvaluatedAt = now;
                opportunity.UpdatedAt = now;
                _opportunityRepository.Update(opportunity);
                archived++;
            }

            await _opportunityRepository.CommitAsync();

            return new PersistResult
            {
                Generated = generated,
                Updated = updated,
                Archived = archived,
                GeneratedByType = createdByType
            };
        }

        private async Task ReplaceSignalsAndRecommendationAsync(Guid opportunityId, OpportunityCandidate candidate, DateTime now)
        {
            var existingSignals = await SafeGetAllAsync(_signalRepository,
                x => x.IsActive == true && x.OpportunityId == opportunityId);

            foreach (var signal in existingSignals)
            {
                signal.IsActive = false;
                signal.UpdatedAt = now;
            }

            if (existingSignals.Count > 0)
                _signalRepository.UpdateRange(existingSignals);

            var existingRecommendation = await SafeGetAllAsync(_recommendationRepository,
                x => x.IsActive == true && x.OpportunityId == opportunityId);

            foreach (var recommendation in existingRecommendation)
            {
                recommendation.IsActive = false;
                recommendation.UpdatedAt = now;
            }

            if (existingRecommendation.Count > 0)
                _recommendationRepository.UpdateRange(existingRecommendation);

            await CreateSignalsAsync(opportunityId, candidate.Signals, now);
            await CreateRecommendationAsync(opportunityId, candidate, now);
        }

