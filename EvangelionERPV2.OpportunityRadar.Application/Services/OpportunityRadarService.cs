                    if (!context.ProductsById.TryGetValue(pair.ProductA, out var productA)
                        || !context.ProductsById.TryGetValue(pair.ProductB, out var productB))
                    {
                        continue;
                    }

                    var trioBonus = trios.Any(trio => trio.Key.Contains(pair.ProductA) && trio.Key.Contains(pair.ProductB))
                        ? 7
                        : 0;

                    var targetPrice = Math.Max(productB.DefaultValue, 0);
                    var estimatedRevenue = Math.Max(0, segmentOrderIds.Count * (pair.Confidence - 0.2) * 0.2 * targetPrice);
                    var estimatedMargin = estimatedRevenue * 0.22;
                    var estimatedCash = estimatedMargin * 0.5;
                    var confidence = Clamp(45 + (pair.Confidence * 35) + (pair.Support * 20) + trioBonus, 0, 100);

                    var fingerprint = $"crosssell:{segmentValue}:{pair.ProductA:N}:{pair.ProductB:N}";

                    opportunities.Add(new OpportunityCandidate
                    {
                        Fingerprint = fingerprint,
                        Type = TypeCrossSell,
                        Title = $"Cross-sell signal for segment {segmentValue}",
                        Description = $"Customers buying {productA.Name} tend to also buy {productB.Name}.",
                        SourceRule = "cross_sell_segment_pair_confidence",
                        SourceModel = "rules-v1",
                        Hypothesis = "Pairs with strong co-purchase in a segment can improve ticket with targeted suggestions.",
                        ExplainabilityJson = JsonSerializer.Serialize(new
                        {
                            segment = segmentValue,
                            productA = productA.Name,
                            productB = productB.Name,
                            supportCount = pair.SupportCount,
                            support = pair.Support,
                            confidence = pair.Confidence
                        }),
                        ConfidenceScore = confidence,
                        EstimatedRevenueImpact = estimatedRevenue,
                        EstimatedMarginImpact = estimatedMargin,
                        EstimatedCashImpact = estimatedCash,
                        RecommendationActionTitle = "Enable segmented cross-sell",
                        RecommendationActionDescription = $"For segment {segmentValue}, add {productB.Name} as suggested item whenever {productA.Name} is in cart.",
                        WhyRecommended = "High co-purchase confidence and recurring support in recent orders.",
                        RecommendationPayloadJson = JsonSerializer.Serialize(new
                        {
                            segment = segmentValue,
                            baseProductId = pair.ProductA,
                            targetProductId = pair.ProductB,
                            confidence = Math.Round(pair.Confidence, 4),
                            support = Math.Round(pair.Support, 4)
                        }),
                        Signals =
                        [
                            new OpportunityCandidateSignal("pair_confidence", $"{pair.ProductA:N}-{pair.ProductB:N}", pair.Confidence, "ratio", "Order", pair.ProductA.ToString()),
                            new OpportunityCandidateSignal("pair_support", $"{pair.ProductA:N}-{pair.ProductB:N}", pair.Support, "ratio", "Order", pair.ProductB.ToString()),
                            new OpportunityCandidateSignal("segment_orders", segmentValue, segmentOrderIds.Count, "orders", "Customer", segmentValue)
                        ]
                    });
                }
            }

            return opportunities;
        }

        private List<OpportunityCandidate> DetectMarginBundles(RadarDataContext context, int minSampleOrders)
        {
            var orderProducts = BuildOrderProductSets(context);
            if (orderProducts.Count == 0)
                return [];

            var averageCostByProduct = BuildAverageCostByProduct(context);
            var dailyConsumption = BuildDailyConsumptionByProduct(context);
            var pairMetrics = BuildPairMetrics(orderProducts, orderProducts.Keys);

            var opportunities = new List<OpportunityCandidate>();

            foreach (var pair in pairMetrics.Where(x => x.SupportCount >= minSampleOrders))
            {
                if (!context.ProductsById.TryGetValue(pair.ProductA, out var productA)
                    || !context.ProductsById.TryGetValue(pair.ProductB, out var productB))
                {
                    continue;
                }

                var productACost = averageCostByProduct.TryGetValue(productA.Id, out var aCost) ? aCost : productA.DefaultValue * 0.78;
                var productBCost = averageCostByProduct.TryGetValue(productB.Id, out var bCost) ? bCost : productB.DefaultValue * 0.78;

                var priceA = Math.Max(0, productA.DefaultValue);
                var priceB = Math.Max(0, productB.DefaultValue);
                var grossPrice = priceA + priceB;

                if (grossPrice <= 0)
                    continue;

                var costTotal = Math.Max(0, productACost + productBCost);
                var bundleMargin = (grossPrice - costTotal) / grossPrice;

                var marginA = priceA <= 0 ? 0 : (priceA - productACost) / priceA;
                var marginB = priceB <= 0 ? 0 : (priceB - productBCost) / priceB;
                var baselineMargin = (marginA + marginB) / 2;
                var marginLift = bundleMargin - baselineMargin;

                if (marginLift <= 0.02)
                    continue;

                var coverageA = ResolveCoverageDays(productA, dailyConsumption);
                var coverageB = ResolveCoverageDays(productB, dailyConsumption);

                if (coverageA < 5 || coverageB < 5)
                    continue;

                var expectedOrders = Math.Max(1, pair.SupportCount * 0.4);
                var bundlePrice = grossPrice * 0.95;
                var estimatedRevenue = expectedOrders * bundlePrice;
                var estimatedMargin = estimatedRevenue * Math.Max(bundleMargin, 0.05);
                var estimatedCash = estimatedMargin * 0.45;

                var confidence = Clamp(40 + (pair.Support * 25) + (pair.Confidence * 25) + (marginLift * 100), 0, 100);
                var fingerprint = $"bundle:{pair.ProductA:N}:{pair.ProductB:N}";

                opportunities.Add(new OpportunityCandidate
                {
                    Fingerprint = fingerprint,
                    Type = TypeBundle,
                    Title = $"Bundle opportunity: {productA.Name} + {productB.Name}",
                    Description = "Suggested kit has stronger consolidated margin and healthy stock coverage.",
                    SourceRule = "bundle_margin_pair_rule",
                    SourceModel = "rules-v1",
                    Hypothesis = "Products bought together with positive margin lift should be sold as bundles.",
                    ExplainabilityJson = JsonSerializer.Serialize(new
                    {
                        productA = productA.Name,
                        productB = productB.Name,
                        bundleMargin = Math.Round(bundleMargin, 4),
                        marginLift = Math.Round(marginLift, 4),
                        coverageA = Math.Round(coverageA, 2),
                        coverageB = Math.Round(coverageB, 2)
                    }),
                    ConfidenceScore = confidence,
                    EstimatedRevenueImpact = estimatedRevenue,
                    EstimatedMarginImpact = estimatedMargin,
                    EstimatedCashImpact = estimatedCash,
                    RecommendationActionTitle = "Create margin-first bundle",
                    RecommendationActionDescription = $"Launch bundle {productA.Name} + {productB.Name} with controlled discount and dedicated campaign.",
                    WhyRecommended = "Bundle margin is above baseline and current coverage does not increase stockout risk.",
                    RecommendationPayloadJson = JsonSerializer.Serialize(new
                    {
                        productIds = new[] { pair.ProductA, pair.ProductB },
                        bundlePrice = Math.Round(bundlePrice, 2),
                        expectedOrders = Math.Round(expectedOrders, 2)
                    }),
                    Signals =
                    [
                        new OpportunityCandidateSignal("bundle_margin", fingerprint, bundleMargin, "ratio", "Product", pair.ProductA.ToString()),
                        new OpportunityCandidateSignal("bundle_margin_lift", fingerprint, marginLift, "ratio", "Product", pair.ProductB.ToString()),
                        new OpportunityCandidateSignal("bundle_support_count", fingerprint, pair.SupportCount, "orders", "Order", pair.ProductA.ToString())
                    ]
                });
            }

            return opportunities
                .OrderByDescending(x => x.EstimatedMarginImpact)
                .Take(5)
                .ToList();
        }

        private List<OpportunityCandidate> DetectSuppressedDemand(RadarDataContext context)
        {
            if (context.OrderedProducts.Count == 0)
                return [];

            var orderById = context.Orders.ToDictionary(x => x.Id, x => x);
            var demandOrderIds = ResolveDemandOrderScope(context.Orders);
            if (demandOrderIds.Count == 0)
                return [];

            var finalizedLines = context.OrderedProducts
                .Where(x => x.OrderId.HasValue
                            && orderById.ContainsKey(x.OrderId.Value)
                            && demandOrderIds.Contains(x.OrderId.Value))
                .ToList();

            if (finalizedLines.Count == 0)
                return [];

            var dailyConsumption = finalizedLines
                .GroupBy(x => x.ProductId)
                .ToDictionary(
                    x => x.Key,
                    x => x.Sum(line => line.Quantity) / Math.Max(1, context.HistoryWindowDays));

            var openDemand = context.OrderedProducts
                .Where(x => x.OrderId.HasValue
                            && orderById.TryGetValue(x.OrderId.Value, out var order)
                            && OpenOrderStatuses.Contains(order.Status))
                .GroupBy(x => x.ProductId)
                .ToDictionary(x => x.Key, x => x.Sum(line => line.Quantity));

            var opportunities = new List<OpportunityCandidate>();

            foreach (var item in dailyConsumption)
            {
                if (!context.ProductsById.TryGetValue(item.Key, out var product))
                    continue;

                var demandPerDay = item.Value;
                if (demandPerDay <= 0)
                    continue;

                var stock = Math.Max(0, product.StorageQuantity);
                var coverageDays = stock / demandPerDay;
                var pendingUnits = openDemand.TryGetValue(product.Id, out var open) ? open : 0;
                var stockoutGap = Math.Max(0, 7 - coverageDays);
                var lostUnits = pendingUnits + (stockoutGap * demandPerDay);

                if (lostUnits <= 1)
                    continue;

                var unitPrice = Math.Max(product.DefaultValue, 0);
                var estimatedRevenue = lostUnits * unitPrice;
                var estimatedMargin = estimatedRevenue * 0.2;
                var estimatedCash = estimatedMargin * 0.65;
                var confidence = Clamp(38 + Math.Min(35, pendingUnits * 2) + (coverageDays <= 1 ? 22 : 12), 0, 100);

                var fingerprint = $"suppressed-demand:{product.Id:N}";

                opportunities.Add(new OpportunityCandidate
                {
                    Fingerprint = fingerprint,
                    Type = TypeSuppressedDemand,
                    Title = $"Suppressed demand risk: {product.Name}",
                    Description = "Demand may be constrained by low stock and open order pressure.",
                    SourceRule = "suppressed_demand_open_orders_stock_gap",
                    SourceModel = "rules-v1",
                    Hypothesis = "Open order pressure and short coverage are a proxy for lost sales due to stockout.",
                    ExplainabilityJson = JsonSerializer.Serialize(new
                    {
                        product = product.Name,
                        pendingUnits,
                        dailyConsumption = Math.Round(demandPerDay, 4),
                        stock = Math.Round(stock, 2),
                        coverageDays = Math.Round(coverageDays, 2),
                        estimatedLostUnits = Math.Round(lostUnits, 2)
                    }),
                    ConfidenceScore = confidence,
                    EstimatedRevenueImpact = estimatedRevenue,
                    EstimatedMarginImpact = estimatedMargin,
                    EstimatedCashImpact = estimatedCash,
                    RecommendationActionTitle = "Replenish and protect availability",
                    RecommendationActionDescription = $"Prioritize replenishment of {product.Name} and reserve stock for open demand.",
                    WhyRecommended = "Coverage is short and demand pressure indicates potential lost revenue.",
                    RecommendationPayloadJson = JsonSerializer.Serialize(new
                    {
                        productId = product.Id,
                        recommendedReplenishment = Math.Round(Math.Max(lostUnits, demandPerDay * 10), 2)
                    }),
                    Signals =
                    [
                        new OpportunityCandidateSignal("coverage_days", product.Id.ToString(), coverageDays, "days", "Product", product.Id.ToString()),
                        new OpportunityCandidateSignal("open_demand_units", product.Id.ToString(), pendingUnits, "units", "Order", product.Id.ToString()),
                        new OpportunityCandidateSignal("lost_units_estimate", product.Id.ToString(), lostUnits, "units", "Order", product.Id.ToString())
                    ]
                });
            }

            return opportunities
                .OrderByDescending(x => x.EstimatedRevenueImpact)
                .Take(8)
                .ToList();
        }

        private List<OpportunityCandidate> DetectLowStock(RadarDataContext context, int minSampleOrders)
        {
            if (context.OrderedProducts.Count == 0 || context.ProductsById.Count == 0)
                return [];

            var orderById = context.Orders.ToDictionary(x => x.Id, x => x);
            var demandOrderIds = ResolveDemandOrderScope(context.Orders);
            if (demandOrderIds.Count < minSampleOrders)
                return [];

            var demandLines = context.OrderedProducts
                .Where(line => line.OrderId.HasValue
                               && orderById.ContainsKey(line.OrderId.Value)
                               && demandOrderIds.Contains(line.OrderId.Value))
                .ToList();

            if (demandLines.Count == 0)
                return [];

            var opportunities = new List<OpportunityCandidate>();
            foreach (var productGroup in demandLines.GroupBy(line => line.ProductId))
            {
                if (!context.ProductsById.TryGetValue(productGroup.Key, out var product))
                    continue;

                var totalSold = productGroup.Sum(line => Math.Max(0, line.Quantity));
                if (totalSold <= 0)
                    continue;

                var salesDates = productGroup
                    .Where(line => line.OrderId.HasValue && orderById.ContainsKey(line.OrderId.Value))
                    .Select(line => orderById[line.OrderId!.Value].CreatedAt.Date)
                    .Distinct()
                    .OrderBy(date => date)
                    .ToList();

                if (salesDates.Count < minSampleOrders)
                    continue;

                var averageDailySales = totalSold / Math.Max(1, context.HistoryWindowDays);
                if (averageDailySales <= 0)
                    continue;

                var intervalDays = new List<double>();
                for (var i = 1; i < salesDates.Count; i++)
                {
                    var interval = (salesDates[i] - salesDates[i - 1]).TotalDays;
                    if (interval > 0)
                        intervalDays.Add(interval);
                }

                var averageIntervalDays = intervalDays.Count == 0 ? 7 : intervalDays.Average();
                var lowStockThresholdDays = Math.Clamp((int)Math.Round(averageIntervalDays * 0.75), 3, 30);

                var currentStock = Math.Max(0, product.StorageQuantity);
                var coverageDays = currentStock / averageDailySales;

                if (coverageDays >= lowStockThresholdDays)
                    continue;

                var coverageGapDays = lowStockThresholdDays - coverageDays;
                var unitsAtRisk = Math.Max(0, coverageGapDays * averageDailySales);
                var suggestedReplenishment = Math.Max(0, (averageDailySales * (lowStockThresholdDays + 2)) - currentStock);
                var unitPrice = Math.Max(0, product.DefaultValue);

                var estimatedRevenue = unitsAtRisk * unitPrice;
                var estimatedMargin = estimatedRevenue * 0.2;
                var estimatedCash = estimatedMargin * 0.5;

                var sampleFactor = Math.Min(1d, salesDates.Count / (double)(minSampleOrders + 2));
                var confidence = Clamp(45 + (sampleFactor * 20) + Math.Min(25, coverageGapDays * 5), 0, 100);
                var fingerprint = $"low-stock:{product.Id:N}";

                opportunities.Add(new OpportunityCandidate
                {
                    Fingerprint = fingerprint,
                    Type = TypeLowStock,
                    Title = $"Low stock risk: {product.Name}",
                    Description = "Stock coverage is below expected threshold based on average sales cadence.",
                    SourceRule = "low_stock_average_sales_coverage",
                    SourceModel = "rules-v1",
                    Hypothesis = "When coverage by average daily sales drops below the inferred threshold, replenishment should be prioritized.",
                    ExplainabilityJson = JsonSerializer.Serialize(new
                    {
                        product = product.Name,
                        averageDailySales = Math.Round(averageDailySales, 4),
                        currentStock = Math.Round(currentStock, 2),
                        coverageDays = Math.Round(coverageDays, 2),
                        lowStockThresholdDays,
                        salesSamples = salesDates.Count
                    }),
                    ConfidenceScore = confidence,
                    EstimatedRevenueImpact = estimatedRevenue,
                    EstimatedMarginImpact = estimatedMargin,
                    EstimatedCashImpact = estimatedCash,
                    RecommendationActionTitle = "Replenish low-stock SKU",
                    RecommendationActionDescription = $"Replenish {product.Name} to recover at least {lowStockThresholdDays} days of coverage.",
                    WhyRecommended = "Coverage is below threshold inferred from the product's average sales pace.",
                    RecommendationPayloadJson = JsonSerializer.Serialize(new
                    {
                        productId = product.Id,
                        suggestedQuantity = Math.Round(suggestedReplenishment, 2),
                        thresholdDays = lowStockThresholdDays,
                        coverageDays = Math.Round(coverageDays, 2)
                    }),
                    Signals =
                    [
                        new OpportunityCandidateSignal("avg_daily_sales", product.Id.ToString(), averageDailySales, "units_per_day", "Order", product.Id.ToString()),
                        new OpportunityCandidateSignal("stock_coverage_days", product.Id.ToString(), coverageDays, "days", "Product", product.Id.ToString()),
                        new OpportunityCandidateSignal("low_stock_threshold_days", product.Id.ToString(), lowStockThresholdDays, "days", "Order", product.Id.ToString())
                    ]
                });
            }

            return opportunities
                .OrderByDescending(x => x.EstimatedMarginImpact)
                .Take(10)
                .ToList();
        }

        private List<OpportunityCandidate> DetectSupplierHiddenCost(RadarDataContext context, int minSampleOrders)
        {
            if (context.PayableBills.Count == 0 || context.PayableItems.Count == 0)
                return [];

            var billById = context.PayableBills.ToDictionary(x => x.Id, x => x);
            var grouped = context.PayableItems
                .Where(item => billById.ContainsKey(item.PayableBillId))
                .GroupBy(item => InferSupplierKey(billById[item.PayableBillId].Description))
                .Select(group =>
                {
                    var bills = group
                        .Select(item => billById[item.PayableBillId])
                        .DistinctBy(bill => bill.Id)
                        .ToList();

                    var quantity = group.Sum(item => item.Quantity);
                    var lineAmount = group.Sum(item => item.LineAmount);
                    var baseUnitCost = quantity <= 0 ? 0 : lineAmount / quantity;

                    var delayDays = bills
                        .Where(bill => bill.ProductsReceivedAt.HasValue)
                        .Select(bill => Math.Max(0, (bill.ProductsReceivedAt!.Value.Date - bill.DueDate.Date).TotalDays))
                        .ToList();

                    var avgDelay = delayDays.Count == 0 ? 0 : delayDays.Average();

                    var extraFreight = bills.Sum(bill =>
                    {
                        var billLines = group.Where(item => item.PayableBillId == bill.Id).Sum(item => item.LineAmount);
                        return Math.Max(0, bill.Amount - billLines);
                    });

                    var reworkRate = ComputeReworkRate(bills, group.ToList());
                    var delayPenalty = baseUnitCost * (avgDelay * 0.01);
                    var reworkPenalty = baseUnitCost * (reworkRate * 0.06);
                    var extraFreightPerUnit = quantity <= 0 ? 0 : extraFreight / quantity;
                    var tco = baseUnitCost + delayPenalty + reworkPenalty + extraFreightPerUnit;

                    return new SupplierCostSnapshot
                    {
                        SupplierKey = group.Key,
                        BillCount = bills.Count,
                        Quantity = quantity,
                        BaseUnitCost = baseUnitCost,
                        AverageDelayDays = avgDelay,
                        ReworkRate = reworkRate,
                        ExtraFreightPerUnit = extraFreightPerUnit,
                        TcoPerUnit = tco
                    };
                })
                .Where(snapshot => snapshot.BillCount >= minSampleOrders && snapshot.Quantity > 0)
                .ToList();

            if (grouped.Count < 2)
                return [];

            var best = grouped.OrderBy(x => x.TcoPerUnit).First();
            var opportunities = new List<OpportunityCandidate>();

            foreach (var supplier in grouped.Where(x => x.SupplierKey != best.SupplierKey))
            {
                var delta = supplier.TcoPerUnit - best.TcoPerUnit;
                if (delta <= 0.01)
                    continue;

                var potentialSavings = delta * supplier.Quantity;
                var confidence = Clamp(35 + (supplier.BillCount * 6) + Math.Min(30, delta * 120), 0, 100);
                var fingerprint = $"supplier-tco:{supplier.SupplierKey}:{best.SupplierKey}";

                opportunities.Add(new OpportunityCandidate
                {
                    Fingerprint = fingerprint,
                    Type = TypeSupplierTco,
                    Title = $"Supplier TCO optimization: {supplier.SupplierKey}",
                    Description = $"Supplier {supplier.SupplierKey} has higher total cost than {best.SupplierKey}.",
                    SourceRule = "supplier_tco_comparison_rule",
                    SourceModel = "rules-v1",
                    Hypothesis = "Suppliers should be ranked by total ownership cost, not only unit price.",
                    ExplainabilityJson = JsonSerializer.Serialize(new
                    {
                        supplier = supplier.SupplierKey,
                        alternative = best.SupplierKey,
                        supplierTco = Math.Round(supplier.TcoPerUnit, 4),
                        bestTco = Math.Round(best.TcoPerUnit, 4),
                        averageDelayDays = Math.Round(supplier.AverageDelayDays, 2),
                        reworkRate = Math.Round(supplier.ReworkRate, 4)
                    }),
                    ConfidenceScore = confidence,
                    EstimatedRevenueImpact = potentialSavings * 1.2,
                    EstimatedMarginImpact = potentialSavings,
                    EstimatedCashImpact = potentialSavings,
                    RecommendationActionTitle = "Prioritize lower-TCO supplier",
                    RecommendationActionDescription = $"Rebalance purchasing volume from {supplier.SupplierKey} to {best.SupplierKey} with controlled transition.",
                    WhyRecommended = "Measured TCO includes delay penalties, rework proxy and extra freight impacts.",
                    RecommendationPayloadJson = JsonSerializer.Serialize(new
                    {
                        supplier = supplier.SupplierKey,
                        suggestedAlternative = best.SupplierKey,
                        estimatedSavings = Math.Round(potentialSavings, 2)
                    }),
                    Signals =
                    [
                        new OpportunityCandidateSignal("supplier_tco", supplier.SupplierKey, supplier.TcoPerUnit, "currency_per_unit", "PayableBill", supplier.SupplierKey),
                        new OpportunityCandidateSignal("best_supplier_tco", best.SupplierKey, best.TcoPerUnit, "currency_per_unit", "PayableBill", best.SupplierKey),
                        new OpportunityCandidateSignal("supplier_avg_delay_days", supplier.SupplierKey, supplier.AverageDelayDays, "days", "PayableBill", supplier.SupplierKey)
                    ]
                });
            }

            return opportunities;
        }

        private List<OpportunityCandidate> DetectCommercialReallocation(RadarDataContext context, int minSampleOrders)
        {
            if (context.Orders.Count < minSampleOrders * 2)
                return [];

            var demandOrderIds = ResolveDemandOrderScope(context.Orders);
            if (demandOrderIds.Count < minSampleOrders)
                return [];

            var averageCostByProduct = BuildAverageCostByProduct(context);

            var groups = context.Orders
                .GroupBy(order =>
                {
                    if (!order.CustomerId.HasValue || !context.CustomersById.TryGetValue(order.CustomerId.Value, out var customer))
                        return "unknown|unknown";

                    return $"{InferSalesChannel(customer)}|{InferRegion(customer.Adress)}";
                })
                .Select(group =>
                {
                    var orders = group.ToList();
                    var finalizedOrders = orders
                        .Where(order => demandOrderIds.Contains(order.Id))
                        .ToList();

                    var orderIds = finalizedOrders.Select(order => order.Id).ToHashSet();
                    var lines = context.OrderedProducts
                        .Where(line => line.OrderId.HasValue && orderIds.Contains(line.OrderId.Value))
                        .ToList();

                    var revenue = finalizedOrders.Sum(order => Math.Max(0, order.TotalValue));
                    var cost = lines.Sum(line =>
                    {
                        var unitCost = averageCostByProduct.TryGetValue(line.ProductId, out var value)
                            ? value
                            : context.ProductsById.TryGetValue(line.ProductId, out var product)
                                ? product.DefaultValue * 0.78
                                : 0;
                        return Math.Max(0, line.Quantity * unitCost);
                    });

                    var margin = Math.Max(0, revenue - cost);
                    var finalizedCount = finalizedOrders.Count;
                    var conversionRate = orders.Count == 0 ? 0 : (double)finalizedCount / orders.Count;
                    var marginPerOrder = finalizedCount == 0 ? 0 : margin / finalizedCount;
                    var revenuePerOrder = finalizedCount == 0 ? 0 : revenue / finalizedCount;

                    return new CommercialGroupSnapshot
                    {
                        GroupKey = group.Key,
                        Orders = orders.Count,
                        FinalizedOrders = finalizedCount,
                        Revenue = revenue,
                        Margin = margin,
                        ConversionRate = conversionRate,
                        MarginPerOrder = marginPerOrder,
                        RevenuePerOrder = revenuePerOrder
                    };
                })
                .Where(snapshot => snapshot.FinalizedOrders >= minSampleOrders)
                .ToList();

            if (groups.Count < 2)
                return [];

            var best = groups
                .OrderByDescending(x => x.MarginPerOrder)
                .ThenByDescending(x => x.ConversionRate)
                .First();

            var worst = groups
                .OrderBy(x => x.MarginPerOrder)
                .ThenBy(x => x.ConversionRate)
                .First();

            if (best.GroupKey == worst.GroupKey)
                return [];

            var marginGap = best.MarginPerOrder - worst.MarginPerOrder;
            if (marginGap <= 1)
                return [];

            var shiftOrders = Math.Max(1, (int)Math.Floor(worst.Orders * 0.15));
            var estimatedMargin = shiftOrders * marginGap;
            var estimatedRevenue = shiftOrders * Math.Max(0, best.RevenuePerOrder - worst.RevenuePerOrder);
            var estimatedCash = estimatedMargin * 0.7;
            var confidence = Clamp(35 + Math.Min(35, marginGap * 3) + Math.Min(30, best.ConversionRate * 40), 0, 100);

            var fingerprint = $"reallocation:{worst.GroupKey}:{best.GroupKey}";
            var hypothesis = "Reallocating sales effort to groups with better margin-per-order can increase profitability.";

            return
            [
                new OpportunityCandidate
                {
                    Fingerprint = fingerprint,
                    Type = TypeCommercialReallocation,
                    Title = "Commercial effort reallocation",
                    Description = $"Move part of effort from {worst.GroupKey} to {best.GroupKey}.",
                    SourceRule = "channel_region_margin_reallocation",
                    SourceModel = "rules-v1",
                    Hypothesis = hypothesis,
                    ExplainabilityJson = JsonSerializer.Serialize(new
                    {
                        fromGroup = worst.GroupKey,
                        toGroup = best.GroupKey,
                        fromMarginPerOrder = Math.Round(worst.MarginPerOrder, 2),
                        toMarginPerOrder = Math.Round(best.MarginPerOrder, 2),
                        fromConversion = Math.Round(worst.ConversionRate, 4),
                        toConversion = Math.Round(best.ConversionRate, 4)
                    }),
                    ConfidenceScore = confidence,
                    EstimatedRevenueImpact = estimatedRevenue,
                    EstimatedMarginImpact = estimatedMargin,
                    EstimatedCashImpact = estimatedCash,
                    RecommendationActionTitle = "Reallocate sales focus",
                    RecommendationActionDescription = $"Reallocate {shiftOrders} planned sales slots from {worst.GroupKey} to {best.GroupKey}.",
                    WhyRecommended = "The destination channel/region shows better margin and conversion proxy.",
                    RecommendationPayloadJson = JsonSerializer.Serialize(new
                    {
                        from = worst.GroupKey,
                        to = best.GroupKey,
                        shiftedOrders = shiftOrders,
                        marginGap = Math.Round(marginGap, 2),
